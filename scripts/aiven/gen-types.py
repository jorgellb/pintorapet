#!/usr/bin/env python3
"""Write src/lib/server/dbTypes.ts: one row type per public table and view, as
the app receives them through src/lib/server/db.ts (timestamps as strings,
bigint/numeric as numbers, json as unknown, enums as string unions).

Usage: python3 scripts/aiven/gen-types.py [local|aiven]
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from conn import ROOT, connect  # noqa: E402

BASE = {
    'uuid': 'string', 'text': 'string', 'character varying': 'string', 'character': 'string', 'citext': 'string',
    'integer': 'number', 'bigint': 'number', 'smallint': 'number', 'numeric': 'number', 'real': 'number',
    'double precision': 'number', 'boolean': 'boolean', 'timestamp with time zone': 'string',
    'timestamp without time zone': 'string', 'date': 'string', 'time without time zone': 'string',
    'jsonb': 'unknown', 'json': 'unknown', 'inet': 'string', 'bytea': 'Uint8Array', 'interval': 'string',
}


def pascal(name: str) -> str:
    return ''.join(part.capitalize() for part in name.split('_'))


def main() -> None:
    target = sys.argv[1] if len(sys.argv) > 1 else 'local'
    with connect(target) as conn:
        conn.read_only = True
        enums = {}
        for name, label in conn.execute("""
            SELECT t.typname, e.enumlabel FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
            JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = 'public'
            ORDER BY t.typname, e.enumsortorder"""):
            enums.setdefault(name, []).append(label)
        columns = conn.execute("""
            SELECT c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
                   (SELECT table_type FROM information_schema.tables t
                    WHERE t.table_schema = c.table_schema AND t.table_name = c.table_name)
            FROM information_schema.columns c WHERE c.table_schema = 'public'
            ORDER BY c.table_name, c.ordinal_position""").fetchall()

    def ts_type(data_type: str, udt: str) -> str:
        if data_type == 'USER-DEFINED':
            return pascal(udt) if udt in enums else 'unknown'
        if data_type == 'ARRAY':
            inner = udt.lstrip('_')
            if inner in enums:
                return f'{pascal(inner)}[]'
            return f"{BASE.get({'int4': 'integer', 'int8': 'bigint', 'uuid': 'uuid', 'text': 'text'}.get(inner, inner), 'unknown')}[]"
        return BASE.get(data_type, 'unknown')

    out = [
        '/**',
        ' * Row types of the public tables and views, as db.ts returns them.',
        ' * Generated by scripts/aiven/gen-types.py — do not edit by hand.',
        ' */',
        '',
    ]
    for name, labels in sorted(enums.items()):
        out.append(f"export type {pascal(name)} = {' | '.join(repr(label) for label in labels)};")
    out.append('')
    tables: dict[str, list[str]] = {}
    kinds: dict[str, str] = {}
    for table, column, data_type, udt, nullable, kind in columns:
        tables.setdefault(table, []).append(
            f"  {column}: {ts_type(data_type, udt)}{' | null' if nullable == 'YES' else ''};")
        kinds[table] = kind
    for table, fields in tables.items():
        comment = 'view' if kinds[table] == 'VIEW' else 'table'
        out.append(f'/** public.{table} ({comment}) */')
        out.append(f'export type {pascal(table)}Row = {{')
        out.extend(fields)
        out.append('};')
        out.append('')
    path = ROOT / 'src' / 'lib' / 'server' / 'dbTypes.ts'
    path.write_text('\n'.join(out))
    print(f'wrote {path.relative_to(ROOT)}: {len(tables)} tables/views, {len(enums)} enums')


if __name__ == '__main__':
    main()
